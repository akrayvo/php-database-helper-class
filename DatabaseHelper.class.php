    /**
     * prepare and execute SQL
     * used internally by public methods to process queries
     * 
     * @return mixed
     */
    private function makeQuery()
    {
        $returnInvalid = $this->getReturnInvalid();

        if ($this->skipQueries) {
            if (empty($this->queryError)) {
                $this->queryError = 'Query skipped due to previous error';
            }
            return  $returnInvalid;
        }

        $sql = $this->sql;
        if (!is_string($sql)) {
            $this->exitProgramError('makeQuery() - $sql is not a string');
            return $returnInvalid;
        }

        // trim the class and function variables
        $this->sql = $sql = trim($sql);
        if (empty($sql)) {
            $this->exitProgramError('makeQuery() - $sql is empty');
            return $returnInvalid;
        }

        $binds = $this->binds;
        // convert any falsy value to an empty array. this allows any falsey (null, false, '') to be passed when there are no binds
        if (empty($binds)) {
            $binds = array();
        }
        if (!is_array($binds)) {
            $this->exitProgramError('makeQuery() - $binds must be an array');
            return $returnInvalid;
        }

        // to avoid mistakes, if delete_and_update_require_where is set, UPDATE and DELETE queries require WHERE
        // note that this is a simple test that sql has the string "WHERE". so "delete from places_where_ive_been;" will incorrectly 
        //    be seen as having a WHERE clause
        if (!empty($this->settings['delete_and_update_require_where'])) {
            // check if it's an UPDATE or DELETE query 
            $sqlFirst6Lc = strtolower(substr($sql, 0, 6));
            if ($sqlFirst6Lc === 'update' || $sqlFirst6Lc === 'delete') {
                // check if the string "WHERE" is in the SQL
                if (stripos($sql, 'where') === false) {
                    $this->exitProgramError(strtoupper($sqlFirst6Lc) . ' query requires a WHERE clause');
                    return $returnInvalid;
                }
            }
        }

        $statement = $this->connection->prepare($sql);
        if (!$statement) {
            //$this->setInfo(false, $statement);
            $this->queryErrorSave($statement);
            return $returnInvalid;
        }

        foreach ($binds as $field => $value) {
            $field = $this->checkIdentifier($field, 'bind field', true);
            if (empty($field)) {
                return $returnInvalid;
            }
            $success =  $statement->bindValue($field, $value);
            if (!$success) {
                $this->queryErrorSave($statement);
                return $returnInvalid;
            }
        }
        $success = $statement->execute();

        if ($this->settings['save_query_run_time']) {
            $this->endTime = microtime(true);
        }

        if (!$success) {
            $this->queryErrorSave($statement);
            return $returnInvalid;
        }

        $this->querySuccessSave($statement);

        return $this->getReturnValue($statement);
    }

    /**
     * process query results and return the appropriate value
     * used internally by makeQuery() to process returned data
     * returns the appropriate invalid value when the query cannot be processed or fails
     * 
     * @param PDOStatement $statement
     * @return string|false
     */
    private function getReturnValue($statement)
    {
        $returnInvalid = $this->getReturnInvalid();

        $type = $this->returnType;

        if (!$statement) {
            return $returnInvalid;
        }

        $keyField = $this->keyField;
        $valueField = $this->valueField;

        if ($type == 'all') {
            $fetchAll = $statement->fetchAll(PDO::FETCH_ASSOC);
            if (empty($keyField)) {
                return $fetchAll;
            }

            $ar = array();
            foreach ($fetchAll as $row) {
                if (!array_key_exists($keyField, $row)) {
                    $this->exitProgramError("key field ($keyField) is not found. available fields: " . implode(', ', array_keys($row)));
                    return $returnInvalid;
                }
                $ar[$row[$keyField]] = $row;
            }
            return $ar;
        }

        if ($type == 'row') {
            $row = $statement->fetch(PDO::FETCH_ASSOC);

            if (!$row) {
                return array();
            }
            return $row;
        }

        if ($type == 'col') {
            $ar = array();
            if (empty($keyField) && empty($valueField)) {
                $val = $statement->fetchColumn();
                while ($val !== false) {
                    $ar[] = $val;
                    $val = $statement->fetchColumn();
                }
                return $ar;
            }

            $fetchAll = $statement->fetchAll(PDO::FETCH_ASSOC);
            foreach ($fetchAll as $row) {
                $k = $v = null;

                if (!empty($valueField)) {
                    if (!array_key_exists($valueField, $row)) {
                        $this->exitProgramError("value field ($valueField) is not found. available fields: " . implode(', ', array_keys($row)));
                        return $returnInvalid;
                    }
                    $v = $row[$valueField];
                } else {
                    $v = reset($row);
                }

                if (!empty($keyField)) {
                    if (!array_key_exists($keyField, $row)) {
                        $this->exitProgramError("key field ($keyField) is not found. available fields: " . implode(', ', array_keys($row)));
                        return $returnInvalid;
                    }
                    $k = $row[$keyField];
                }

                if (!is_null($k)) {
                    $ar[$k] = $v;
                } else {
                    $ar[] = $v;
                }
            }
            return $ar;
        }

        if ($type == 'one') {
            if (empty($valueField)) {
                $row = $statement->fetch(PDO::FETCH_NUM);
                if ($row) {
                    return $row[0];
                }
            } else {
                $row = $statement->fetch(PDO::FETCH_ASSOC);
                if ($row) {
                    if (!array_key_exists($valueField, $row)) {
                        $this->exitProgramError("value field ($valueField) is not found. available fields: " . implode(', ', array_keys($row)));
                        return $returnInvalid;
                    }
                    return $row[$valueField];
                }
            }
            return '';
        }

        if ($type == 'insert') {
            return $this->insertId;
        }

        return true;
    }

    /**
     * determine the value to return when a query fails or returns no results
     * used internally by makeQuery() and getReturnValue()
     * returns null for errors when the return_null_on_error setting is enabled
     * otherwise returns a value based on the requested return type
     * 
     * @return mixed
     */
    private function getReturnInvalid()
    {
        $type = $this->returnType;

        if ($type === 'query' || $type === 'insertMultiple') {
            //  note that "query" and "insertMultiple" have boolean return values (success or fail). 
            //      no need for them to be null even if return_null_on_error is set
            return false;
        }
        if ($this->settings['return_null_on_error']) {
            return null;
        }
        if ($type === 'one') {
            return '';
        }
        if ($type === 'insert') {
            return 0;
        }

        return array();
    }

    /**
     * after an error, set error information
     * calls exitProgramError
     * 
     * @param PDOStatement $statement
     */
    private function queryErrorSave($statement)
    {
        $errorMsg = 'Query Failed';
        if ($statement) {
            $e  = $statement->errorInfo();
            if (!empty($e)) {
                $errorMsg = implode(' | ', $e);
            }
        } else {
            $e = $this->connection->errorInfo();
            if (!empty($e)) {
                $errorMsg = implode(' | ', $e);
            }
        }
        $this->exitProgramError($errorMsg);
    }

    /**
     * after a successful query, save query information
     * set isSuccess. set rowCount if applicable. set insertId if applicable
     * 
     * @param PDOStatement $statement
     */
    private function querySuccessSave($statement)
    {
        $this->isSuccess = true;
        if ($statement) {
            $rowCount = $statement->rowCount();
            if (!empty($rowCount)) {
                $this->rowCount = $rowCount;
            }
        }

        $sqlFirst6Lc = strtolower(substr(trim($this->sql), 0, 6));
        $type = $this->returnType;
        if ($type === 'insert' || $type === 'insertMultiple' || $sqlFirst6Lc == 'insert') {
            $this->insertId = $this->connection->lastInsertId();
        }
    }

    /**
     * check if a value is a raw SQL value created by the raw() 
     * checks the array('raw_sql'=> $value) format generated by the raw() function
     * returns the raw SQL string or false if the value is not a valid raw SQL value
     *
     * @param mixed $value
     * @return string|false
     */
    private function getRawString($value)
    {
        if (!is_array($value)) {
            return false;
        }
        if (count($value) != 1) {
            return false;
        }
        if (!isset($value['raw_sql'])) {
            return false;
        }
        return $value['raw_sql'];
    }

    /**
     * check a database identifier such as a table or field name
     * should only contain letters, numbers, and underscores.
     * for binds, remove colon, check identifier, and put colon back. this will make sure that the colon will 
     *      not be seen as an invalid character and the colon will be added if it wasn't set in the first place 
     *      ":name" and "name" will both return ":name"
     * if invalid, produce an error (will end the program depending on settings)
     * if invalid and the program settings do not end the program on error, return an empty string.
     * 
     * @param string $identifier
     * @param string $type
     * @param boolean $isBind
     * @return string
     */
    private function checkIdentifier($identifier, $type, $isBind = false)
    {
        if (!is_string($identifier)) {
            $message = $type . ' is not a string (' . gettype($identifier) . ' passed)';
            $this->exitProgramError($message);
            return '';
        }

        if ($isBind) {
            $identifier = ltrim($identifier, ':');
        }

        if (empty($identifier)) {
            $message = $type . ' is empty';
            $this->exitProgramError($message);
            return '';
        }

        if (!preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*$/', $identifier)) {
            $message = $type . ' is invalid: ' . $identifier
                . ' | must contain only letters, numbers, and underscores and cannot start with a number';
            $this->exitProgramError($message);
            return '';
        }

        if ($isBind) {
            $identifier = ':' . $identifier;
        }

        return $identifier;
    }

    /**
     * reset information for the current database operation
     */
    private function resetInfo()
    {
        $this->insertId = 0;
        $this->sql = '';
        $this->isSuccess = false;
        $this->rowCount = 0;
        $this->returnType = '';
        $this->binds = array();
        $this->keyField = '';
        $this->valueField = '';
        $this->queryError = '';
        $this->endTime = 0;
        if ($this->settings['save_query_run_time']) {
            $this->startTime = microtime(true);
        } else {
            $this->startTime = 0;
        }
    }

    /**
     * handle a database connection or query error.
     * $isConnectionError is true for connection, initialization, or configuration errors
     * end program (with optional output), continue without database, or continue with database based on settings
     * see connection_error_action, query_error_action, error_output_html, and output_error_debugging settings
     * 
     * @param string $errorMessage
     * @param boolean $isConnectionError
     */
    private function exitProgramError($errorMessage = '', $isConnectionError = false)
    {
        $endProgram = false;
        if ($isConnectionError) {
            $this->lastConnectionError = $errorMessage;
            $this->skipQueries = true;
            if ($this->settings['connection_error_action'] === 'continue_without_database') {
                // continue
            } else {
                $endProgram = true;
            }
        } else {
            $this->queryError = $this->lastQueryError = $errorMessage;
            if ($this->settings['query_error_action'] === 'continue_with_database') {
                // continue
            } elseif ($this->settings['query_error_action'] === 'continue_without_database') {
                $this->skipQueries = true;
            } else {
                $endProgram = true;
            }
        }

        if (!$endProgram) {
            return;
        }

        // output and end the program

        $errorHtml = 'Database Error';
        if (!empty($this->settings['error_output_html'])) {
            $errorHtml = $this->settings['error_output_html'];
        }
        echo "\n\n<br>\n<br>\n<div>\n" . $errorHtml . "</div>";

        if ($this->settings['output_error_debugging']) {
            echo "\n\n<br>\n<br>\n<div>\n" . htmlentities($errorMessage) . "</div><br>\n\n";

            if (!$isConnectionError) {
                $this->displayLastQueryInfo();
            }

            echo "<br>\n\n";

            $backtrace = debug_backtrace();
            $backtraceData = array();
            $databaseHelperFile = realpath(__FILE__);
            foreach ($backtrace as $bt) {
                $file = $line = $function = $class = $args = '';

                if (!empty($bt['file'])) {
                    $file = $bt['file'];
                }

                if (realpath($file) ==  $databaseHelperFile) {
                    // filter out anything in the class itself (this file) 
                    //continue;
                }

                if (!empty($bt['line'])) {
                    $line = $bt['line'];
                }
                if (!empty($bt['class'])) {
                    $class = $bt['class'];
                }
                if (!empty($bt['function'])) {
                    $function = $bt['function'];
                }


                $backtraceData[] = array(
                    'file' => $file,
                    'line' =>  $line,
                    'function' => $function,
                    'class' => $class
                );
            }
            $this->display($backtraceData);
        }

        die();
    }


