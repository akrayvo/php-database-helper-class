    // Modify Database (Insert, Update, Delete, Alter, etc) From Parameters (converted to SQL)

    // insert a new row into a table
    public static function insert($table, $values)
    {
        self::resetInfo();
        self::$returnType = 'insert';

        $returnInvalid = self::getReturnInvalid();
        $table = self::checkIdentifier($table, 'insert() table');
        if (empty($table)) {
            return $returnInvalid;
        }

        if (!is_array($values)) {
            self::exitProgramError('insert() - $values is not an array (' . gettype($values) . ' passed)');
            return $returnInvalid;
        }
        if (count($values) < 1) {
            self::exitProgramError('insert() - $values array is empty (0 values)');
            return $returnInvalid;
        }

        $fieldStr = $valueStr = '';
        $binds = array();
        $sep = '';
        foreach ($values as $field => $value) {
            $field = self::checkIdentifier($field, 'insert() field (array key)');
            if (empty($field)) {
                return $returnInvalid;
            }
            $fieldStr .= $sep . '`' . $field . '`';
            $rawSql = self::getRawString($value);
            if ($rawSql) {
                $valueStr .= $sep . ' ' . $rawSql . ' ';
            } else {
                $valueStr .= $sep . ':' . $field;
                $binds[':' . $field] = $value;
            }
            $sep = ', ';
        }
        self::$sql = 'INSERT INTO `' . $table . '` (' . $fieldStr . ') VALUES (' . $valueStr . ');';
        self::$binds = $binds;

        return self::makeQuery();
    }

    // insert a new row into a table
    public static function insertMultiple($table, $rows)
    {
        self::resetInfo();
        self::$returnType = 'insertMultiple';

        $returnInvalid = self::getReturnInvalid();

        $table = self::checkIdentifier($table, 'insertMultiple() table');
        if (empty($table)) {
            return $returnInvalid;
        }

        if (!is_array($rows)) {
            self::exitProgramError('insertMultiple() - $rows is not an array (' . gettype($rows) . ' passed)');
            return $returnInvalid;
        }
        if (count($rows) < 1) {
            self::exitProgramError('InsertMultiple() - $rows array is empty (0 rows)');
            return $returnInvalid;
        }

        // default value, will change after inserts
        $returnValue = $returnInvalid;

        // pre-check all rows
        $matchRow = array();
        $rowKeys = array();
        $matchRowCount = 0;
        foreach ($rows as $row) {
            if (!is_array($row)) {
                self::exitProgramError('InsertMultiple() - $rows is not a 2 dimensional array');
                return $returnInvalid;
            }

            if (empty($matchRow)) {
                // our first row that we will use to compare to others has not been set yet
                // do some validation and set it

                if (count($row) < 1) {
                    self::exitProgramError('InsertMultiple() - the first row in $rows is empty (0 fields)');
                    return $returnInvalid;
                }
                foreach ($row as $field => $value) {
                    $fieldClean = self::checkIdentifier($field, 'insertMultiple() row field (array key)', true);
                    if (empty($fieldClean)) {
                        self::exitProgramError('InsertMultiple() - $row has a row with an invalid field name (array key)');
                        return $returnInvalid;
                    }
                }

                // $matchRow will be compared with every other row, in these checks keys must be the same
                $matchRow = $row;
                $matchRowCount = count($matchRow);
                $rowKeys = array_keys($matchRow);
            } else {
                if ($matchRowCount !== count($row)  || array_diff_key($row, $matchRow)) {
                    self::exitProgramError('InsertMultiple() - mismatched field name (array key) in $rows');
                    return $returnInvalid;
                }
            }
        }

        $fieldStr = '';
        foreach ($rowKeys as $key) {
            if (!empty($fieldStr)) {
                $fieldStr .= ',';
            }
            $fieldStr .= '`' . $key . '`';
        }

        $maxInsertRows = intval(self::$settings['max_records_per_insert_query']);

        $valStr = '';
        $binds = array();
        $ctr = 0;
        $isFirstRow = true;
        foreach ($rows as $row) {
            $ctr++;
            if ($isFirstRow) {
                $isFirstRow = false;
            } else {
                $valStr .= ',';
            }

            $isFirstField = true;
            $valStr .= '(';
            $fieldCtr = 0;
            foreach ($rowKeys as $field) {
                $fieldCtr++;
                if ($isFirstField) {
                    $isFirstField = false;
                } else {
                    $valStr .= ',';
                }
                $rawSql = self::getRawString($row[$field]);
                if ($rawSql) {
                    $valStr .= ' ' . $rawSql . ' ';
                } else {
                    $bindKey = ':v' . $ctr . '_' . $fieldCtr;
                    $valStr .= $bindKey;
                    $binds[$bindKey] = $row[$field];
                }
            }
            $valStr .= ')';

            if ($ctr >= $maxInsertRows) {
                self::$sql = 'insert into `' . $table . '` (' . $fieldStr . ') values ' . $valStr . ';';
                self::$binds = $binds;
                $returnValue = self::makeQuery();
                if (!$returnValue) {
                    return $returnInvalid;
                }
                // reset to start building next insert
                $isFirstRow = true;
                $valStr = '';
                $binds = array();
                $ctr = 0;
            }
        }

        if (!empty($valStr)) {
            // insert remaining unprocessed records
            self::$sql = 'insert into `' . $table . '` (' . $fieldStr . ') values ' . $valStr . ';';
            self::$binds = $binds;
            $returnValue = self::makeQuery();
            if (!$returnValue) {
                return $returnInvalid;
            }
        }

        return $returnValue;
    }

    // insert multiple new rows into a table using a separate array of field names
    public static function insertMultipleFieldsValues($table, $fields, $dataRows)
    {
        self::resetInfo();
        self::$returnType = 'insertMultiple';

        $returnInvalid = self::getReturnInvalid();

        $table = self::checkIdentifier($table, 'insertMultipleFieldsValues() table');
        if (empty($table)) {
            return $returnInvalid;
        }

        if (!is_array($fields)) {
            self::exitProgramError('insertMultipleFieldsValues() - $fields is not an array (' . gettype($fields) . ' passed)');
            return $returnInvalid;
        }

        $fieldCount = count($fields);
        if ($fieldCount < 1) {
            self::exitProgramError('insertMultipleFieldsValues() - $fields array is empty (0 fields)');
            return $returnInvalid;
        }
        if (count(array_unique($fields)) !== $fieldCount) {
            self::exitProgramError('insertMultipleFieldsValues() - $fields values must be unique');
            return $returnInvalid;
        }

        if (!is_array($dataRows)) {
            self::exitProgramError('insertMultipleFieldsValues() - $dataRows is not an array (' . gettype($dataRows) . ' passed)');
            return $returnInvalid;
        }
        if (count($dataRows) < 1) {
            self::exitProgramError('insertMultipleFieldsValues() - $dataRows array is empty (0 rows)');
            return $returnInvalid;
        }

        // default value, will change after inserts
        $returnValue = $returnInvalid;

        // pre-check all rows

        foreach ($dataRows as $row) {
            if (!is_array($row)) {
                self::exitProgramError('insertMultipleFieldsValues() - $dataRows is not a 2 dimensional array');
                return $returnInvalid;
            }

            if ($fieldCount !== count($row)) {
                self::exitProgramError('insertMultipleFieldsValues() - mismatched field count in $dataRows rows');
                return $returnInvalid;
            }
        }

        $fieldStr = '';
        foreach ($fields as $field) {
            $field = self::checkIdentifier($field, 'insertMultipleFieldsValues() field');
            if (empty($field)) {
                return $returnInvalid;
            }

            if (!empty($fieldStr)) {
                $fieldStr .= ',';
            }
            $fieldStr .= '`' . $field . '`';
        }

        $maxInsertRows = intval(self::$settings['max_records_per_insert_query']);

        $valStr = '';
        $binds = array();
        $ctr = 0;
        $isFirstRow = true;
        foreach ($dataRows as $row) {
            $ctr++;
            if ($isFirstRow) {
                $isFirstRow = false;
            } else {
                $valStr .= ',';
            }

            $isFirstField = true;
            $valStr .= '(';
            $valCtr = 0;
            foreach ($row as $value) {
                if ($isFirstField) {
                    $isFirstField = false;
                } else {
                    $valStr .= ',';
                }
                $valCtr++;

                $rawSql = self::getRawString($value);
                if ($rawSql) {
                    $valStr .= ' ' . $rawSql . ' ';
                } else {
                    $bindKey = ':v' . $ctr . '_' . $valCtr;
                    $valStr .= $bindKey;
                    $binds[$bindKey] = $value;
                }
            }
            $valStr .= ')';

            if ($ctr >= $maxInsertRows) {
                self::$sql = 'insert into `' . $table . '` (' . $fieldStr . ') values ' . $valStr . ';';
                self::$binds = $binds;
                $returnValue = self::makeQuery();
                if (!$returnValue) {
                    return $returnInvalid;
                }

                // reset to start building next insert
                $isFirstRow = true;
                $valStr = '';
                $binds = array();
                $ctr = 0;
            }
        }

        if (!empty($valStr)) {
            self::$sql = 'insert into `' . $table . '` (' . $fieldStr . ') values ' . $valStr . ';';
            self::$binds = $binds;
            $returnValue = self::makeQuery();
            if (!$returnValue) {
                return $returnInvalid;
            }
        }

        return $returnValue;
    }

    // update rows in a table
    public static function update($table, $values, $whereSql, $whereBinds = array())
    {
        self::resetInfo();
        self::$returnType = 'query';

        $returnInvalid = self::getReturnInvalid();

        $table = self::checkIdentifier($table, 'update() table');
        if (empty($table)) {
            return $returnInvalid;
        }

        if (!is_array($values)) {
            self::exitProgramError('update() - $values is not an array (' . gettype($values) . ' passed)');
            return $returnInvalid;
        }
        if (count($values) < 1) {
            self::exitProgramError('update() - $values array is empty (0 values)');
            return $returnInvalid;
        }

        if (!is_string($whereSql)) {
            self::exitProgramError('update() - $whereSql is not a string (' . gettype($whereSql) . ' passed)');
            return $returnInvalid;
        }
        if (empty($whereSql)) {
            self::exitProgramError('update() - $whereSql is empty');
            return $returnInvalid;
        }


        $setStr = '';
        $binds = $whereBinds;
        $ctr = 0;
        foreach ($values as $field => $value) {
            $ctr++;
            $field = self::checkIdentifier($field, 'update() field');
            if (empty($field)) {
                return $returnInvalid;
            }

            if (!empty($setStr)) {
                $setStr .= ',';
            }
            $bindKey = ':v' . $ctr;
            while (isset($binds[$bindKey]) || isset($binds[ltrim($bindKey, ':')])) {
                // there was a collision in the naming, move on to the next counter.
                $ctr++;
                $bindKey = ':v' . $ctr;
            }
            $rawSql = self::getRawString($value);
            if ($rawSql !== false) {
                $setStr .= '`' . $field . '`=' . $rawSql . ' ';
            } else {
                $setStr .= '`' . $field . '`=' . $bindKey;
                $binds[$bindKey] = $value;
            }
        }

        self::$sql = 'UPDATE `' . $table . '` SET ' . $setStr . ' WHERE ' . $whereSql . ';';
        self::$binds = $binds;
        return self::makeQuery();
    }

    // update a row in a table using its identifier field (usually "id")
    public static function updateById($table, $values, $id)
    {
        // reset needed even though the update function will reset again.
        // but if errors are generated in this function, we don't want previous query info in debugging output
        self::resetInfo();
        self::$returnType = 'query';

        $returnInvalid = self::getReturnInvalid();

        $table = self::checkIdentifier($table, 'updateById() table');
        if (empty($table)) {
            return $returnInvalid;
        }
        $idFieldName = self::checkIdentifier(self::$settings['id_field_name'], 'updateById() id_field_name setting');
        if (empty($idFieldName)) {
            return $returnInvalid;
        }

        $whereSql = '`' . $idFieldName . '`=:id';
        $binds = array(':id' => $id);
        return self::update($table, $values, $whereSql, $binds);
    }

    // delete a row from a table using its identifier field (usually "id")
    public static function deleteById($table, $id)
    {
        self::resetInfo();
        self::$returnType = 'query';

        $returnInvalid = self::getReturnInvalid();

        $table = self::checkIdentifier($table, 'deleteById() table');
        $idFieldName = self::checkIdentifier(self::$settings['id_field_name'], 'deleteById() id_field_name setting');
        if (empty($table) || empty($idFieldName)) {
            return $returnInvalid;
        }

        self::$sql = 'DELETE FROM `' . $table . '` WHERE `' . $idFieldName . '`=:id;';
        self::$binds = array(':id' => $id);

        return self::makeQuery();
    }


