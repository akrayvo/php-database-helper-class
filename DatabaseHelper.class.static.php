    // display information about the last query
    public static function displayLastQueryInfo()
    {
        $ar = array(
            'type' => self::$returnType,
            'sql' => self::$sql,
            'binds' => self::$binds,
            'keyField' => self::$keyField,
            'valueField' => self::$valueField,
            'rowCount' => self::$rowCount,
            'insertId' => self::$insertId,
            'isSuccess' => self::$isSuccess,
            'queryError' => self::$queryError
        );
        if (self::$settings['save_query_run_time']) {
            $duration = 0;
            if (self::$startTime && self::$endTime) {
                $duration = self::$endTime - self::$startTime;
            }
            $ar['duration'] = number_format($duration, 6) . ' seconds';
        }

        self::display($ar);
    }

