    // display a value for debugging
    private static function displayInternal($value, $isTopLevel = true)
    {
        if ($isTopLevel) {
            echo "\n<style>" .
                ".db_class_preview1 { background-color: #DEF; margin:14px 0; } " .
                "pre.db_class_preview1 { padding: 8px 4px; border:1px solid #777;padding: 0; } " .
                ".db_class_preview1 pre.db_class_preview1 { border: none; padding:0; margin:0 } " .
                "table.db_class_preview1 { border-collapse: collapse; } " .
                "table.db_class_preview1 td, table.db_class_preview1 th { padding: 6px 10px; border: 1px solid #777; } " .
                "table.db_class_preview1 td td { padding: 4px; border: 1px solid #AAA; } " .
                ".db_class_preview1 table.db_class_preview1 { margin:0 } " .
                "</style>\n";
        }

        if (!is_array($value)) {

            if (
                $isTopLevel ||
                (empty($value) && $value !== 0 && $value !== 0.0 && $value !== '0') ||
                (!is_string($value) && !is_int($value) && !is_float($value))
            ) {
                echo "\n<pre class=\"db_class_preview1\">";
                var_dump($value);
                echo "</pre>\n";
            } else {
                echo htmlspecialchars($value);
            }

            return;
        }

        $count = count($value);
        if ($count < 1 || $count > intval(self::$settings['max_rows_for_table_display'])) {
            echo "\n<pre class=\"db_class_preview1\">";
            var_dump($value);
            echo "</pre>\n";
            return;
        }

        $is2DArray = true;
        $matchCols = $colKeys = array();
        $colCount  = 0;
        foreach ($value as $row) {

            if (!is_array($row) || count($row) < 1) {
                $is2DArray = false;
                break;
            }

            if ($colCount === 0) {
                // $matchCols will be compared with columns in every other row, in these checks keys must be the same
                $matchCols = $row;
                $colCount = count($row);
                $colKeys = array_keys($row);
            } else {
                if ($colCount !== count($row) || array_diff_key($row, $matchCols)) {
                    $is2DArray = false;
                    break;
                }
            }

            foreach ($row as $col) {
                if (!is_string($col) && !is_int($col) && !is_float($col) && !is_null($col)) {
                    $is2DArray = false;
                    break 2;
                }
            }
        }


        if ($is2DArray) {
            echo "\n<table class=\"db_class_preview1\"><thead><tr><th><i>key</i></th>";
            foreach ($colKeys as $colKey) {
                echo "<th>" . htmlspecialchars($colKey) . "</th>";
            }
            echo "</tr></thead>\n";
            echo "<tbody>\n";
            foreach ($value as $k => $v) {
                echo "<tr><td>" . htmlspecialchars($k) . "</td>";
                foreach ($v as $v2) {
                    if (is_null($v2)) {
                        echo "<td><i>NULL</i></td>";
                    } else {
                        echo "<td>" . htmlspecialchars($v2) . "</td>";
                    }
                }
                echo "</tr>\n";
            }

            echo "</tbody></table>\n";
            return;
        }

        echo "\n<table class=\"db_class_preview1\"><tbody>\n";
        foreach ($value as $k => $v) {
            echo "<tr><td>" . htmlspecialchars($k) . "</td><td>";
            self::displayInternal($v, false);
            echo "</td></tr>\n";
        }
        echo "</tbody></table>\n";
    }
