    // Internal Processing Functions (Queries)

    // prepare and execute SQL
    private static function makeQuery()
    {
        $returnInvalid = self::getReturnInvalid();

        if (self::$skipQueries) {
            if (empty(self::$queryError)) {
                self::$queryError = 'Query skipped due to previous error';
            }
            return  $returnInvalid;
        }

        $sql = self::$sql;
        if (!is_string($sql)) {
            self::exitProgramError('makeQuery() - $sql is not a string');
            return $returnInvalid;
        }

        // trim the class and function variables
        self::$sql = $sql = trim($sql);
        if (empty($sql)) {
            self::exitProgramError('makeQuery() - $sql is empty');
            return $returnInvalid;
        }

        $binds = self::$binds;
        // convert any falsy value to an empty array. this allows any falsey (null, false, '') to be passed when there are no binds
        if (empty($binds)) {
            $binds = array();
        }
        if (!is_array($binds)) {
            self::exitProgramError('makeQuery() - $binds must be an array');
            return $returnInvalid;
        }

        // to avoid mistakes, if delete_and_update_require_where is set, UPDATE and DELETE queries require WHERE
        // note that this is a simple test that sql has the string "WHERE". so "delete from places_where_ive_been;" will incorrectly 
        //    be seen as having a WHERE clause
        if (!empty(self::$settings['delete_and_update_require_where'])) {
            // check if it's an UPDATE or DELETE query 
            $sqlFirst6Lc = strtolower(substr($sql, 0, 6));
            if ($sqlFirst6Lc === 'update' || $sqlFirst6Lc === 'delete') {
                // check if the string "WHERE" is in the SQL
                if (stripos($sql, 'where') === false) {
                    self::exitProgramError(strtoupper($sqlFirst6Lc) . ' query requires a WHERE clause');
                    return $returnInvalid;
                }
            }
        }

        $statement = self::$connection->prepare($sql);
        if (!$statement) {
            //self::$setInfo(false, $statement);
            self::queryErrorSave($statement);
            return $returnInvalid;
        }

        foreach ($binds as $field => $value) {
            $field = self::checkIdentifier($field, 'bind field', true);
            if (empty($field)) {
                return $returnInvalid;
            }
            $success =  $statement->bindValue($field, $value);
            if (!$success) {
                self::queryErrorSave($statement);
                return $returnInvalid;
            }
        }
        $success = $statement->execute();

        if (self::$settings['save_query_run_time']) {
            self::$endTime = microtime(true);
        }

        if (!$success) {
            self::queryErrorSave($statement);
            return $returnInvalid;
        }

        self::querySuccessSave($statement);

        return self::getReturnValue($statement);
    }

    // process query results and return the appropriate value
    private static function getReturnValue($statement)
    {
        $returnInvalid = self::getReturnInvalid();

        $type = self::$returnType;

        if (!$statement) {
            return $returnInvalid;
        }

        $keyField = self::$keyField;
        $valueField = self::$valueField;

        if ($type == 'all') {
            $fetchAll = $statement->fetchAll(PDO::FETCH_ASSOC);
            if (empty($keyField)) {
                return $fetchAll;
            }

            $ar = array();
            foreach ($fetchAll as $row) {
                if (!array_key_exists($keyField, $row)) {
                    self::exitProgramError("key field ($keyField) is not found. available fields: " . implode(', ', array_keys($row)));
                    return $returnInvalid;
                }
                $ar[$row[$keyField]] = $row;
            }
            return $ar;
        }

        if ($type == 'row') {
            $row = $statement->fetch(PDO::FETCH_ASSOC);

            if (!$row) {
                return array();
            }
            return $row;
        }

        if ($type == 'col') {
            $ar = array();
            if (empty($keyField) && empty($valueField)) {
                $val = $statement->fetchColumn();
                while ($val !== false) {
                    $ar[] = $val;
                    $val = $statement->fetchColumn();
                }
                return $ar;
            }

            $fetchAll = $statement->fetchAll(PDO::FETCH_ASSOC);
            foreach ($fetchAll as $row) {
                $k = $v = null;

                if (!empty($valueField)) {
                    if (!array_key_exists($valueField, $row)) {
                        self::exitProgramError("value field ($valueField) is not found. available fields: " . implode(', ', array_keys($row)));
                        return $returnInvalid;
                    }
                    $v = $row[$valueField];
                } else {
                    $v = reset($row);
                }

                if (!empty($keyField)) {
                    if (!array_key_exists($keyField, $row)) {
                        self::exitProgramError("key field ($keyField) is not found. available fields: " . implode(', ', array_keys($row)));
                        return $returnInvalid;
                    }
                    $k = $row[$keyField];
                }

                if (!is_null($k)) {
                    $ar[$k] = $v;
                } else {
                    $ar[] = $v;
                }
            }
            return $ar;
        }

        if ($type == 'one') {
            if (empty($valueField)) {
                $row = $statement->fetch(PDO::FETCH_NUM);
                if ($row) {
                    return $row[0];
                }
            } else {
                $row = $statement->fetch(PDO::FETCH_ASSOC);
                if ($row) {
                    if (!array_key_exists($valueField, $row)) {
                        self::exitProgramError("value field ($valueField) is not found. available fields: " . implode(', ', array_keys($row)));
                        return $returnInvalid;
                    }
                    return $row[$valueField];
                }
            }
            return '';
        }

        if ($type == 'insert') {
            return self::$insertId;
        }

        return true;
    }

    // determine the value to return when a query fails or returns no results
    private static function getReturnInvalid()
    {
        $type = self::$returnType;

        if ($type === 'query' || $type === 'insertMultiple') {
            return false;
        }
        if (self::$settings['return_null_on_error']) {
            return null;
        }
        if ($type === 'one') {
            return '';
        }
        if ($type === 'insert') {
            return 0;
        }

        return array();
    }

    // after an error, set error information
    private static function queryErrorSave($statement)
    {
        $errorMsg = 'Query Failed';
        if ($statement) {
            $e  = $statement->errorInfo();
            if (!empty($e)) {
                $errorMsg = implode(' | ', $e);
            }
        } else {
            $e = self::$connection->errorInfo();
            if (!empty($e)) {
                $errorMsg = implode(' | ', $e);
            }
        }
        self::exitProgramError($errorMsg);
    }

    // after a successful query, save query information
    private static function querySuccessSave($statement)
    {
        self::$isSuccess = true;
        if ($statement) {
            $rowCount = $statement->rowCount();
            if (!empty($rowCount)) {
                self::$rowCount = $rowCount;
            }
        }

        $sqlFirst6Lc = strtolower(substr(trim(self::$sql), 0, 6));
        $type = self::$returnType;
        if ($type === 'insert' || $type === 'insertMultiple' || $sqlFirst6Lc == 'insert') {
            self::$insertId = self::$connection->lastInsertId();
        }
    }

    // check if a value is a raw SQL value created by the raw() 
    private static function getRawString($value)
    {
        if (!is_array($value)) {
            return false;
        }
        if (count($value) != 1) {
            return false;
        }
        if (!isset($value['raw_sql'])) {
            return false;
        }
        return $value['raw_sql'];
    }

    // check a database identifier such as a table or field name
    private static function checkIdentifier($identifier, $type, $isBind = false)
    {
        if (!is_string($identifier)) {
            $message = $type . ' is not a string (' . gettype($identifier) . ' passed)';
            self::exitProgramError($message);
            return '';
        }

        if ($isBind) {
            $identifier = ltrim($identifier, ':');
        }

        if (empty($identifier)) {
            $message = $type . ' is empty';
            self::exitProgramError($message);
            return '';
        }

        if (!preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*$/', $identifier)) {
            $message = $type . ' is invalid: ' . $identifier
                . ' | must contain only letters, numbers, and underscores and cannot start with a number';
            self::exitProgramError($message);
            return '';
        }

        if ($isBind) {
            $identifier = ':' . $identifier;
        }

        return $identifier;
    }

    // reset information for the current database operation
    private static function resetInfo()
    {
        self::$insertId = 0;
        self::$sql = '';
        self::$isSuccess = false;
        self::$rowCount = 0;
        self::$returnType = '';
        self::$binds = array();
        self::$keyField = '';
        self::$valueField = '';
        self::$queryError = '';
        self::$endTime = 0;
        if (self::$settings['save_query_run_time']) {
            self::$startTime = microtime(true);
        } else {
            self::$startTime = 0;
        }
    }

    // handle a database connection or query error.
    private static function exitProgramError($errorMessage = '', $isConnectionError = false)
    {
        $endProgram = false;
        if ($isConnectionError) {
            self::$lastConnectionError = $errorMessage;
            self::$skipQueries = true;
            if (self::$settings['connection_error_action'] === 'continue_without_database') {
                // continue
            } else {
                $endProgram = true;
            }
        } else {
            self::$queryError = self::$lastQueryError = $errorMessage;
            if (self::$settings['query_error_action'] === 'continue_with_database') {
                // continue
            } elseif (self::$settings['query_error_action'] === 'continue_without_database') {
                self::$skipQueries = true;
            } else {
                $endProgram = true;
            }
        }

        if (!$endProgram) {
            return;
        }

        // output and end the program

        $errorHtml = 'Database Error';
        if (!empty(self::$settings['error_output_html'])) {
            $errorHtml = self::$settings['error_output_html'];
        }
        echo "\n\n<br>\n<br>\n<div>\n" . $errorHtml . "</div>";

        if (self::$settings['output_error_debugging']) {
            echo "\n\n<br>\n<br>\n<div>\n" . htmlentities($errorMessage) . "</div><br>\n\n";

            if (!$isConnectionError) {
                self::displayLastQueryInfo();
            }

            echo "<br>\n\n";

            $backtrace = debug_backtrace();
            $backtraceData = array();
            $databaseHelperFile = realpath(__FILE__);
            foreach ($backtrace as $bt) {
                $file = $line = $function = $class = $args = '';

                if (!empty($bt['file'])) {
                    $file = $bt['file'];
                }

                if (realpath($file) ==  $databaseHelperFile) {
                    // filter out anything in the class itself (this file) 
                    continue;
                }

                if (!empty($bt['line'])) {
                    $line = $bt['line'];
                }
                if (!empty($bt['class'])) {
                    $class = $bt['class'];
                }
                if (!empty($bt['function'])) {
                    $function = $bt['function'];
                }


                $backtraceData[] = array(
                    'file' => $file,
                    'line' =>  $line,
                    'function' => $function,
                    'class' => $class
                );
            }
            self::display($backtraceData);
        }

        die();
    }


